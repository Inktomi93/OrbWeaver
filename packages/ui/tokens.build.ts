/** A pointer-conditional override: the token's fine-pointer value (DTCG `$extensions["orb.pointerFine"]`). */
interface FineOverride {
  readonly path: readonly string[];
  readonly value: string;
  /** The token's own `orb.output` role is `snapped` — the override inherits the device-pixel belt (#1640). */
  readonly snapped: boolean;
}

/** `["color","user-bubble"]` → `--color-user-bubble` (group name IS the Tailwind v4 namespace). */
function cssVarName(path: readonly string[]): string {
  return `--${path.join("-")}`;
}

function objectValue(value: unknown, path: string): Record<string, unknown> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new Error(`${path}: expected a structured DTCG value`);
  }
  return value as Record<string, unknown>;
}

function finiteNumber(value: unknown, path: string): number {
  if (typeof value !== "number" || !Number.isFinite(value)) {
    throw new Error(`${path}: expected a finite number`);
  }
  return value;
}

function renderColor(value: unknown, path: string): string {
  const color = objectValue(value, path);
  if (color["colorSpace"] !== "oklch" || !Array.isArray(color["components"]) || color["components"].length !== OKLCH_COMPONENT_COUNT) {
    throw new Error(`${path}: Orb's CSS emitter supports only contract-valid OKLCH colors`);
  }
  const components = color["components"].map((component, index) => finiteNumber(component, `${path}.components[${index}]`));
  const alpha = color["alpha"] === undefined ? "" : ` / ${finiteNumber(color["alpha"], `${path}.alpha`)}`;
  return `oklch(${components.join(" ")}${alpha})`;
}

function renderDimension(value: unknown, path: string, unitlessZero = false): string {
  const dimension = objectValue(value, path);
  const amount = finiteNumber(dimension["value"], `${path}.value`);
  if (dimension["unit"] !== "px" && dimension["unit"] !== "rem") {
    throw new Error(`${path}: unsupported dimension unit ${JSON.stringify(dimension["unit"])}`);
  }
  return unitlessZero && amount === 0 ? "0" : `${amount}${dimension["unit"]}`;
}

function renderDuration(value: unknown, path: string): string {
  const duration = objectValue(value, path);
  const amount = finiteNumber(duration["value"], `${path}.value`);
  if (duration["unit"] !== "ms" && duration["unit"] !== "s") {
    throw new Error(`${path}: unsupported duration unit ${JSON.stringify(duration["unit"])}`);
  }
  return `${amount}${duration["unit"]}`;
}

function renderFontFamily(value: unknown, path: string): string {
  const members = Array.isArray(value) ? value : [value];
  return members
    .map((member, index) => {
      if (typeof member !== "string") {
        throw new Error(`${path}[${index}]: expected one font-family name`);
      }
      return /\s/u.test(member) ? `'${member}'` : member;
    })
    .join(", ");
}

function renderCubicBezier(value: unknown, path: string): string {
  if (!Array.isArray(value) || value.length !== CUBIC_BEZIER_COORDINATE_COUNT) {
    throw new Error(`${path}: expected four cubic-bezier coordinates`);
  }
  return `cubic-bezier(${value.map((coordinate, index) => finiteNumber(coordinate, `${path}[${index}]`)).join(", ")})`;
}

function renderShadow(value: unknown, path: string): string {
  const layers = Array.isArray(value) ? value : [value];
  return layers
    .map((layerValue, index) => {
      const layerPath = `${path}[${index}]`;
      const layer = objectValue(layerValue, layerPath);
      const parts = [
        layer["inset"] === true ? "inset" : "",
        renderDimension(layer["offsetX"], `${layerPath}.offsetX`, true),
        renderDimension(layer["offsetY"], `${layerPath}.offsetY`, true),
        renderDimension(layer["blur"], `${layerPath}.blur`, true),
      ];
      const spread = renderDimension(layer["spread"], `${layerPath}.spread`, true);
      if (spread !== "0") {
        parts.push(spread);
      }
      parts.push(renderColor(layer["color"], `${layerPath}.color`));
      return parts.filter(Boolean).join(" ");
    })
    .join(", ");
}

function resolvedValue(token: TransformedToken): unknown {
  return token.$value ?? token.value;
}

/**
 * The device-pixel belt's ONE serialization (docs/design/integer-line-boxes.md §3b). Both arms of a
 * snapped token spell it here — the `@theme` base value and the `@media (pointer: fine)` override —
 * so the belt cannot be applied to half a token.
 */
function snappedSerialization(length: string): string {
  return `round(up, ${length}, 1px)`;
}

function renderPortableToken(token: TransformedToken, contractToken: ContractToken, lightToken: ContractToken | undefined): string | null {
  const path = contractToken.pathString;
  switch (contractToken.outputRole) {
    case "input":
      return null;
    case "percentage":
      return `${finiteNumber(resolvedValue(token), path)}%`;
    case "snapped":
      // The device-pixel belt (docs/design/integer-line-boxes.md §3b): a snapped dimension is authored
      // integer at the 16px root and emitted through round() so every --font-scale value — the slider is
      // continuous — resolves the box back onto the device-pixel grid. Identity at the default scale.
      //
      // THE STRATEGY IS `up`, NOT THE DEFAULT `nearest` (#1160, measured 2026-09-05). Snapping to the
      // NEAREST integer may round a box DOWN by up to half a pixel while the paired font size scales
      // continuously, which drops the resolved RATIO below the ratified leading floor
      // (`LEADING_FLOOR` = leading.label / text.label = 16/13 ≈ 1.2308) — a defect no authored value can
      // see. Measured on `settings:appearance --appearance-preset reading` (--font-scale 1.25, root
      // 20px): text.micro resolves 13.125px and `round(0.8125rem, 1px)` resolved 16px, ratio 1.219 —
      // four `tight-leading` findings on the setting-row gloss. `up` never shrinks the box, so the
      // resolved ratio is always ≥ the AUTHORED ratio and the floor holds at every stop of the slider;
      // and because every snapped token is authored integer at the 16px root (the gate's ARM T), `up` is
      // still the identity at the default scale. `nearest` also broke leading.label on text.label, whose
      // authored ratio IS the floor exactly — half a pixel of slack in either direction is below it.
      return snappedSerialization(renderDimension(resolvedValue(token), path));
    case "light-dark":
      if (lightToken === undefined) {
        throw new Error(`${path}: light-dark output has no Light arm`);
      }
      return `light-dark(${renderColor(lightToken.value, `${path}.light`)}, ${renderColor(resolvedValue(token), `${path}.dark`)})`;
    case null:
      break;
  }
  switch (contractToken.type) {
    case "color":
      return renderColor(resolvedValue(token), path);
    case "dimension":
      return renderDimension(resolvedValue(token), path);
    case "duration":
      return renderDuration(resolvedValue(token), path);
    case "fontFamily":
      return renderFontFamily(resolvedValue(token), path);
    case "shadow":
      return renderShadow(resolvedValue(token), path);
    case "cubicBezier":
      return renderCubicBezier(resolvedValue(token), path);
    case "number":
      return `${finiteNumber(resolvedValue(token), path)}`;
    case "fontWeight":
    case "strokeStyle":
    case "border":
    case "transition":
    case "gradient":
    case "typography":
      throw new Error(`${path}: standard type ${contractToken.type} has no Orb CSS serialization arm`);
    case null:
      throw new Error(`${path}: token escaped contract type validation`);
  }
}

function generatedPolarityArms(token: TransformedToken, contractToken: ContractToken, lightToken: ContractToken | undefined): readonly GeneratedPolarityArms[] {
  if (contractToken.outputRole !== "light-dark") {
    return [];
  }
  const path = contractToken.pathString;
  if (lightToken === undefined) {
    throw new Error(`${path}: light-dark output has no Light arm`);
  }
  return [
    {
      path: token.path,
      light: renderColor(lightToken.value, `${path}.light`),
      dark: renderColor(resolvedValue(token), `${path}.dark`),
    },
  ];
}

function outputPath(target: string): readonly string[] {
  const [group, ...rest] = target.slice(2).split("-");
  if (group === undefined || rest.length === 0) {
    throw new Error(`orb.cssValues target ${target} cannot map to an Orb token path`);
  }
  return [group, rest.join("-")];
}

function resolveCssValue(value: string, portableByPath: ReadonlyMap<string, string>): string {
  const alias = DTCG_ALIAS_RE.exec(value)?.[1];
  if (alias === undefined) {
    return value;
  }
  const resolved = portableByPath.get(alias);
  if (resolved === undefined) {
    throw new Error(`orb.cssValues alias ${JSON.stringify(alias)} escaped contract portability validation`);
  }
  return resolved;
}

function renderThemeCss(tokens: readonly GeneratedCssValue[]): string {
  const lines = tokens.map((t) => `  ${cssVarName(t.path)}: ${t.value};`);
  return `/* ${HEADER}\n */\n@theme {\n${lines.join("\n")}\n}\n`;
}

function renderRootCss(tokens: readonly GeneratedCssValue[]): string {
  if (tokens.length === 0) {
    return "";
  }
  const lines = tokens.map((token) => `  ${cssVarName(token.path)}: ${token.value};`);
  return `\n:root {\n${lines.join("\n")}\n}\n`;
}

export function renderGeneratedCss(tokens: readonly GeneratedCssValue[]): string {
  return renderThemeCss(tokens.filter((token) => token.placement === "theme")) + renderRootCss(tokens.filter((token) => token.placement === "root"));
}

/**
 * The pointer-conditional override block (D62 P1, UI-Arch §4b axis 3). The `@theme` block above
 * carries the COARSE-first control heights (the ≥44px touch floor holds by default); fine pointers
 * narrow them here. Emitted UNLAYERED on purpose: an unlayered `:root` custom-property override
 * beats the `@layer theme` value regardless of source order (verified against the Tailwind v4
 * compiler), so the fine values win wherever a `height: var(--spacing-control-*)` utility resolves.
 * The narrowed values live in `tokens.json` (`$extensions["orb.pointerFine"]`) — this script carries
 * no design literals.
 *
 * THE BELT REACHES THIS BLOCK TOO (#1640). A fine override REPLACES the `@theme` value, so a snapped
 * token whose fine arm is emitted bare is unbelted on exactly the pointer most sessions use — which is
 * where #1143's off-grid switch thumb lived (`--spacing-switch-thumb` 1.125rem × 0.875 font-scale =
 * 15.75px, halved by `items-center` to a 7.875px offset). Every override of a snapped token therefore
 * carries the same `round(up, …, 1px)` serialization as its base arm; anything else is half a belt.
 */
function renderPointerFineBlock(overrides: readonly FineOverride[]): string {
  if (overrides.length === 0) {
    return "";
  }
  const lines = overrides.map((o) => `    ${cssVarName(o.path)}: ${o.snapped ? snappedSerialization(o.value) : o.value};`);
  return `\n@media (pointer: fine) {\n  :root {\n${lines.join("\n")}\n  }\n}\n`;
}

/** Does this raw DTCG node carry the `snapped` output role? (contract-validated; read here for the fine arm). */
function hasSnappedOutput(node: Record<string, unknown>): boolean {
  const output = (node["$extensions"] as Record<string, unknown> | undefined)?.["orb.output"];
  return typeof output === "object" && output !== null && (output as Record<string, unknown>)["kind"] === "snapped";
}

/** Collect the contract-validated pointer-fine dimensions from the raw DTCG source. */
function collectPointerFine(node: Record<string, unknown>, path: readonly string[], out: FineOverride[]): void {
  if ("$value" in node) {
    const ext = (node["$extensions"] as Record<string, unknown> | undefined)?.["orb.pointerFine"];
    if (typeof ext === "object" && ext !== null) {
      const value = (ext as Record<string, unknown>)["value"];
      const unit = (ext as Record<string, unknown>)["unit"];
      if (typeof value !== "number" || (unit !== "px" && unit !== "rem")) {
        throw new Error(`orb.pointerFine at ${path.join(".")} escaped contract validation`);
      }
      // The role is read off the SAME node the override rides (the contract validated both keys),
      // so the fine arm cannot drift out of the belt its base arm is in.
      out.push({ path, value: `${value}${unit}`, snapped: hasSnappedOutput(node) });
    }
    return;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$") || typeof child !== "object" || child === null) {
      continue;
    }
    collectPointerFine(child as Record<string, unknown>, [...path, key], out);
  }
}

/** A snapped-output dimension's resolved px at the 16px root (docs/design/integer-line-boxes.md §3b). */
interface SnappedBasePx {
  readonly path: readonly string[];
  readonly px: number;
}

function snappedBasePx(token: TransformedToken, path: string): SnappedBasePx {
  const dimension = objectValue(resolvedValue(token), path);
  const amount = finiteNumber(dimension["value"], `${path}.value`);
  return { path: token.path, px: dimension["unit"] === "rem" ? amount * ROOT_REM_PX : amount };
}

function renderTokensTs(tokens: readonly GeneratedCssValue[], polarityArms: readonly GeneratedPolarityArms[], snapped: readonly SnappedBasePx[]): string {
  const entries = tokens.map((t) => {
    const key = t.path.join(".");
    return `  "${key}": { cssVar: "${cssVarName(t.path)}", value: ${JSON.stringify(t.value)} },`;
  });
  const varOpen = "`var(${";
  const varClose = "TOKENS[path].cssVar})`";
  const armEntries = polarityArms.map(
    (token) => `  ${JSON.stringify(token.path.join("."))}: { light: ${JSON.stringify(token.light)}, dark: ${JSON.stringify(token.dark)} },`,
  );
  return [
    `/** ${HEADER} */`,
    "",
    "/** Token → `{ cssVar, value }`: `cssVar` for CSS (theme-overridable); `value` is the static literal, for consumers that can't resolve `var()` (canvas chart libs, `parseFloat`). */",
    "export const TOKENS = {",
    ...entries,
    "} as const;",
    "",
    "export type TokenPath = keyof typeof TOKENS;",
    "",
    "/** Concrete arms for every polarity-aware token. CSS consumers use TOKENS[path].value; canvas/build-time consumers use this generated surface and never parse light-dark() serialization. */",
    "export const TOKEN_POLARITY_ARMS = {",
    ...armEntries,
    "} as const;",
    "",
    "export type PolarityTokenPath = keyof typeof TOKEN_POLARITY_ARMS;",
    "",
    "/** Resolved px at the 16px root for every snapped-output dimension — build-time consumers (the ui-audit ramp bindings) read THIS and never parse the round() serialization (the TOKEN_POLARITY_ARMS precedent). */",
    "export const SNAPPED_LENGTH_BASE_PX = {",
    ...snapped.map((token) => `  ${JSON.stringify(token.path.join("."))}: ${token.px},`),
    "} as const;",
    "",
    "export type SnappedTokenPath = keyof typeof SNAPPED_LENGTH_BASE_PX;",
    "",
    "/** The `snapped` serialization and its INVERSE are generated together (#1640): a runtime consumer that must read a LIVE",
    " *  custom property — the pointer-conditional arm no static map carries — gets the belted length decoded here rather than",
    " *  re-spelling `round(up, …, 1px)` at the call site. Accepts a bare `<n>rem`/`<n>px` too (an unsnapped token); returns",
    " *  null for anything else, so a caller falls back instead of inventing a number. */",
    "export function snappedLengthPx(value: string, rootFontSizePx: number): number | null {",
    "  const trimmed = value.trim();",
    "  const belted = /^round\\(up,\\s*(?<length>[^,]+),\\s*1px\\)$/u.exec(trimmed);",
    '  const length = (belted?.groups?.["length"] ?? trimmed).trim();',
    "  const magnitude = Number.parseFloat(length);",
    "  if (!Number.isFinite(magnitude)) {",
    "    return null;",
    "  }",
    '  const px = length.endsWith("rem") ? magnitude * rootFontSizePx : length.endsWith("px") ? magnitude : null;',
    "  return px === null || belted === null ? px : Math.ceil(px);",
    "}",
    "",
    "/** `var(--…)` reference for a token — the ONE way runtime code names a token. */",
    "export function cssVar(path: TokenPath): string {",
    `  return ${varOpen}${varClose};`,
    "}",
    "",
    "/** The seed [data-theme] value-sets — their own generated module (see tokens.build.ts), re-exported here so `@orb/ui/tokens` stays the ONE import for every token surface. */",
    `export { SEED_THEME_VALUE_SETS } from "${THEMES_MODULE}";`,
    "",
  ].join("\n");
}

/** A loaded + validated seed value-set: its `[data-theme]` name, native color-scheme, and ordered vars. */
interface SeedTheme {
  readonly name: string;
  readonly colorScheme: "light" | "dark";
  /** `[--color-…, oklch(…)]` in the value-set's own key order (drives both the CSS and the TS emit). */
  readonly vars: ReadonlyArray<readonly [name: string, value: string]>;
}

/**
 * Select the two shipped seed palettes from the bounded Resolver result. Light also carries the
 * polarity arms used to compose light-dark(); those are not `[data-theme]` overrides. Every other
 * value-set member must be exactly the ThemeScope emit surface plus color.backdrop.
 */
function loadSeedThemes(contract: TokenContractResult): SeedTheme[] {
  const baseByPath = new Map(contract.baseTokens.map((token) => [token.pathString, token]));
  return contract.themes
    .filter((theme) => theme.source !== "base")
    .map((theme) => {
      const tokens = theme.source === "light" ? contract.lightTokens : contract.mochaTokens;
      const present = new Set([...tokens.keys()].filter((path) => SEED_VALUE_SET_PATHS.has(path)));
      const missing = [...SEED_VALUE_SET_PATHS].filter((path) => !present.has(path));
      const extra = [...tokens.keys()].filter(
        (path) => !(SEED_VALUE_SET_PATHS.has(path) || (theme.source === "light" && baseByPath.get(path)?.outputRole === "light-dark")),
      );
      if (missing.length > 0 || extra.length > 0) {
        throw new Error(
          `seed value-set ${theme.source}: token paths must be exactly the emitted colors + color.backdrop (plus Light polarity arms) — missing [${missing.join(
            ", ",
          )}], extra [${extra.join(", ")}]`,
        );
      }
      return {
        name: theme.id,
        colorScheme: theme.colorScheme,
        vars: [...tokens]
          .filter(([path]) => SEED_VALUE_SET_PATHS.has(path))
          .map(([path, token]) => [`--${path.replace(".", "-")}`, renderColor(token.value, path)] as const),
      };
    });
}

/**
 * The seed-theme block, emitted AFTER the pointer-fine block. The base `:root { color-scheme: dark }`
 * is emitted FIRST here (moved out of globals.css) so the light seed's `color-scheme: light` flip wins
 * by source order within this one generated file. Each `[data-theme]` block is unlayered + self-complete.
 */
function renderSeedThemesBlock(themes: readonly SeedTheme[]): string {
  const parts = ["\n:root {\n  color-scheme: dark;\n}\n"];
  for (const theme of themes) {
    const lines = theme.vars.map(([name, value]) => `  ${name}: ${value};`);
    parts.push(`\n[data-theme="${theme.name}"] {\n  color-scheme: ${theme.colorScheme};\n${lines.join("\n")}\n}\n`);
  }
  return parts.join("");
}

/** The generated `themes.gen.ts` module — the seed palettes as a typed TS record (parallel to TOKENS),
 *  re-exported by index.ts. Its own file so a growing palette roster never pushes the token map past the
 *  `component-size-ui` cap (see the header). */
function renderSeedThemesTs(themes: readonly SeedTheme[]): string {
  const lines = [
    `/** ${HEADER} */`,
    "",
    "/** The seed [data-theme] value-sets, GENERATED from src/tokens/themes/*.json — the same palettes theme.css emits as `[data-theme=…]` blocks, exposed to TS (e.g. the theme picker) so a seed palette has ONE source. */",
    "export const SEED_THEME_VALUE_SETS = {",
  ];
  for (const theme of themes) {
    lines.push(`  ${JSON.stringify(theme.name)}: {`);
    lines.push(`    colorScheme: ${JSON.stringify(theme.colorScheme)},`);
    lines.push("    vars: {");
    for (const [name, value] of theme.vars) {
      lines.push(`      ${JSON.stringify(name)}: ${JSON.stringify(value)},`);
    }
    lines.push("    },");
    lines.push("  },");
  }
  lines.push("} as const;");
  lines.push("");
  return lines.join("\n");
}

export async function generateArtifacts(uiRoot = HERE): Promise<{ themeCss: string; tokensTs: string; themesTs: string }> {
  const source = JSON.parse(readFileSync(join(uiRoot, "src/tokens/tokens.json"), "utf8")) as DesignTokens;
  const lightSource = JSON.parse(readFileSync(join(uiRoot, "src/tokens/themes/light.json"), "utf8")) as Record<string, unknown>;
  const contract = assertTokenContract(uiRoot, join(uiRoot, "../.."));
  // Runs on RAW sources, before resolution: references remain distinguishable from independent literals,
  // and the split polarity values can still be judged as one two-arm decision.
  assertNoNearDuplicateColors(source as unknown as Record<string, unknown>, { lightSource });
  const sd = new StyleDictionary({
    tokens: source,
    usesDtcg: true,
    log: { verbosity: "silent" },
    platforms: { flat: { files: [] } },
  });
  const dictionary = await sd.getPlatformTokens("flat");
  const contractByPath = new Map(contract.baseTokens.map((token) => [token.pathString, token]));
  const flat: GeneratedCssValue[] = [];
  const polarityArms: GeneratedPolarityArms[] = [];
  const snapped: SnappedBasePx[] = [];
  for (const token of dictionary.allTokens) {
    const path = token.path.join(".");
    const contractToken = contractByPath.get(path);
    if (contractToken === undefined) {
      throw new Error(`Style Dictionary emitted undeclared token ${path}`);
    }
    const value = renderPortableToken(token, contractToken, contract.lightTokens.get(path));
    if (value !== null) {
      flat.push({ path: token.path, value, placement: "theme" });
    }
    if (contractToken.outputRole === "snapped") {
      snapped.push(snappedBasePx(token, path));
    }
    polarityArms.push(...generatedPolarityArms(token, contractToken, contract.lightTokens.get(path)));
  }
  if (dictionary.allTokens.length !== contract.baseTokens.length) {
    throw new Error(`Style Dictionary token coverage ${dictionary.allTokens.length} != contract ${contract.baseTokens.length}`);
  }
  const portableByPath = new Map(flat.map((token) => [token.path.join("."), token.value]));
  for (const [target, entry] of Object.entries(contract.cssValues)) {
    flat.push({ path: outputPath(target), value: resolveCssValue(entry.value, portableByPath), placement: entry.placement });
  }
  const emittedTargets = new Set(flat.map((token) => cssVarName(token.path)));
  if (emittedTargets.size !== flat.length || emittedTargets.size !== contract.cssTargets.size) {
    throw new Error(`emitter target coverage ${emittedTargets.size}/${flat.length} != contract ${contract.cssTargets.size}`);
  }
  const missing = [...contract.cssTargets].filter((target) => !emittedTargets.has(target));
  if (missing.length > 0) {
    throw new Error(`emitter omitted contract targets: ${missing.join(", ")}`);
  }
  if (flat.some((token) => token.value.includes("[object Object]"))) {
    throw new Error("type-directed token emission produced [object Object]");
  }
  const fine: FineOverride[] = [];
  collectPointerFine(source as unknown as Record<string, unknown>, [], fine);
  const seedThemes = loadSeedThemes(contract);
  return {
    themeCss: renderGeneratedCss(flat) + renderPointerFineBlock(fine) + renderSeedThemesBlock(seedThemes),
    tokensTs: renderTokensTs(flat, polarityArms, snapped),
    themesTs: renderSeedThemesTs(seedThemes),
  };
}

// tsx entrypoint (`pnpm --filter @orb/ui tokens:build`): write the committed artifacts.
if (process.argv[1]?.endsWith("tokens.build.ts")) {
  const { themeCss, tokensTs, themesTs } = await generateArtifacts();
  writeFileSync(THEME_CSS, themeCss);
  writeFileSync(TOKENS_TS, tokensTs);
  writeFileSync(THEMES_TS, themesTs);
}
