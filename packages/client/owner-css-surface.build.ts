// Writes owner-css-surface.ts, the manifest of the names owner custom CSS may target (UI-Theming-and-Content.md §12.1).
// The slot and shell-class tuples are harvested from source; the token and ThemeScope rosters are imported live.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(HERE, "../..");

export const OWNER_CSS_SURFACE_PATHS = {
  manifest: "packages/client/owner-css-surface.ts",
  producer: "packages/client/owner-css-surface.build.ts",
  shellCss: "packages/client/src/features/app-shell/surfaces/shell.css",
  shellRegions: "packages/client/src/features/app-shell/surfaces/shell",
  sourceRoots: ["packages/ui/src", "packages/client/src"],
} as const;

const HEADER = `// GENERATED by owner-css-surface.build.ts — DO NOT EDIT.
// Regenerate: pnpm --filter @orb/client surface:build (freshness is test-enforced).`;

/** A `data-slot` value the DOM carries that no source literal spells whole: built from a prefix or chosen at runtime. */
export interface ComputedSlot {
  readonly name: string;
  /** The file that builds it, relative to the repository root. */
  readonly site: string;
  /** The literal that file spells; a rename or a move reds the pin test. */
  readonly fragment: string;
}

const CHART_SLOTS = ["bar-list", "heatmap", "histogram", "scatter"] as const;
const METADATA_SLOTS = ["output-cap", "tokens", "cache", "id", "gen-duration", "ttft"] as const;

/** The runtime-built slot names, each with the site that builds it. */
export const COMPUTED_SLOTS: readonly ComputedSlot[] = [
  ...CHART_SLOTS.flatMap((chart) =>
    ["heading", "data"].map((part) => ({
      name: `${chart}-${part}`,
      site: "packages/ui/src/charts/labeled-chart-frame/labeled-chart-frame.tsx",
      fragment: `\${slot}-${part}`,
    })),
  ),
  ...METADATA_SLOTS.map((part) => ({
    name: `message-metadata-${part}`,
    site: "packages/client/src/features/chat/components/message-metadata-row.tsx",
    fragment: `metadatum("message-metadata-${part}"`,
  })),
  { name: "guide-chip", site: "packages/client/src/features/rpg/components/tracker-blocks/tracker-blocks.tsx", fragment: '"guide-chip"' },
  { name: "tracker-chip", site: "packages/client/src/features/rpg/components/tracker-blocks/tracker-blocks.tsx", fragment: '"tracker-chip"' },
  // biome-ignore lint/suspicious/noTemplateCurlyInString: the fragment is the template source the site spells.
  { name: "regex-usage-presets", site: "packages/client/src/features/regex/components/regex-context-body.tsx", fragment: "regex-usage-${noun}" },
  // biome-ignore lint/suspicious/noTemplateCurlyInString: the fragment is the template source the site spells.
  { name: "regex-usage-characters", site: "packages/client/src/features/regex/components/regex-context-body.tsx", fragment: "regex-usage-${noun}" },
];

/** One source file the harvest reads. */
export interface SurfaceSource {
  readonly path: string;
  readonly text: string;
}

export interface SurfaceInput {
  readonly sources: readonly SurfaceSource[];
  readonly shellCss: string;
}

// Every spelling that puts a literal slot name on an element: the attribute, the props-object key, the `slot`/`dataSlot`
// prop a wrapper forwards, and a `*_SLOT` constant a wrapper reads.
const SLOT_LITERAL_PATTERNS = [
  /\bdata-slot="([a-z0-9-]+)"/gu,
  /"data-slot": "([a-z0-9-]+)"/gu,
  /\b(?:slot|dataSlot)="([a-z0-9-]+)"/gu,
  /\b[A-Z][A-Z_]*_SLOT = "([a-z0-9-]+)"/gu,
];
const SHELL_CLASS_PATTERN = /\.(shell-[a-z0-9-]+)/gu;

function harvest(text: string, patterns: readonly RegExp[], into: Set<string>): void {
  for (const pattern of patterns) {
    for (const match of text.matchAll(pattern)) {
      const name = match[1];
      if (name !== undefined) {
        into.add(name);
      }
    }
  }
}

function tuple(name: string, members: Iterable<string>): string {
  const lines = [...members].sort().map((member) => `  "${member}",`);
  return `export const ${name} = [\n${lines.join("\n")}\n] as const;`;
}

/** The manifest text for the given sources; pure, so a test can plant a rename. */
export function renderOwnerCssSurface({ sources, shellCss }: SurfaceInput): string {
  const slots = new Set<string>(COMPUTED_SLOTS.map((slot) => slot.name));
  for (const source of sources) {
    harvest(source.text, SLOT_LITERAL_PATTERNS, slots);
  }
  const shellClasses = new Set<string>();
  harvest(shellCss, [SHELL_CLASS_PATTERN], shellClasses);
  return [
    HEADER,
    'import { THEME_SCOPE_EMIT_VARS } from "@orb/ui/theme-scope/emit-vars";',
    'import { TOKENS } from "@orb/ui/tokens";',
    "",
    "/** Every `data-slot` value the app renders. */",
    tuple("OWNER_CSS_SLOTS", slots),
    "",
    "/** Every `.shell-*` class shell.css styles. */",
    tuple("OWNER_CSS_SHELL_CLASSES", shellClasses),
    "",
    "/** Every custom property theme.css serves on the document; the ramp primitives are private and unserved. */",
    "export const OWNER_CSS_TOKEN_VARS: readonly string[] = Object.values(TOKENS)",
    "  .map((token) => token.cssVar)",
    '  .filter((cssVar) => !cssVar.startsWith("--primitive-"));',
    "",
    "/** Every custom property a ThemeScope writes for a carried or custom theme. */",
    "export const OWNER_CSS_THEME_SCOPE_VARS = THEME_SCOPE_EMIT_VARS;",
    "",
  ].join("\n");
}

function* sourceFiles(root: string, extension = /\.tsx?$/u): Generator<string> {
  for (const entry of readdirSync(root, { recursive: true, withFileTypes: true })) {
    if (entry.isFile() && extension.test(entry.name) && !entry.parentPath.includes("node_modules")) {
      yield join(entry.parentPath, entry.name);
    }
  }
}

/** The live sources under the repository root, in a stable order. */
export function readOwnerCssSources(repoRoot = REPO_ROOT): SurfaceInput {
  const paths = OWNER_CSS_SURFACE_PATHS.sourceRoots.flatMap((root) => [...sourceFiles(join(repoRoot, root))]).sort();
  return {
    sources: paths.map((path) => ({ path: relative(repoRoot, path), text: readFileSync(path, "utf8") })),
    shellCss: [
      OWNER_CSS_SURFACE_PATHS.shellCss,
      ...[...sourceFiles(join(repoRoot, OWNER_CSS_SURFACE_PATHS.shellRegions), /\.css$/u)].sort().map((path) => relative(repoRoot, path)),
    ]
      .map((path) => readFileSync(join(repoRoot, path), "utf8"))
      .join("\n"),
  };
}

if (process.argv[1]?.endsWith("owner-css-surface.build.ts")) {
  writeFileSync(join(REPO_ROOT, OWNER_CSS_SURFACE_PATHS.manifest), renderOwnerCssSurface(readOwnerCssSources()));
}
