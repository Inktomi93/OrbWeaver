// Writes appearance-channel.gen.css: the registered `--appearance-*` properties and the `appearance-*` variants for
// every root-carried setting, generated from the manifest's channels and the contract's bounds, values and defaults.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { appearanceSettingsSchema } from "@orb/contracts/settings/appearance";
import type { AppearanceChannelRow } from "./src/lib/appearance-carrier-manifest.ts";
import { APPEARANCE_CHANNEL_ROWS } from "./src/lib/appearance-carrier-manifest.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(HERE, "../..");

export const APPEARANCE_CHANNEL_PATHS = {
  css: "packages/client/src/styles/appearance-channel.gen.css",
  producer: "packages/client/appearance-channel.build.ts",
} as const;

const HEADER = `/* GENERATED by appearance-channel.build.ts — DO NOT EDIT.
 * Regenerate: pnpm --filter @orb/client appearance:build (freshness is test-enforced). */`;

/** The parts of a zod leaf the generator reads; zod 4 keeps them on `_zod.def`. */
interface LeafDef {
  readonly type: string;
  readonly innerType?: SchemaNode;
  readonly out?: SchemaNode;
  readonly element?: SchemaNode;
  readonly entries?: Readonly<Record<string, string>>;
}
interface SchemaNode {
  readonly _zod: { readonly def: LeafDef };
  /** Set on a number schema: its `.min()` and `.max()` bounds, or null when unbounded. */
  readonly minValue?: number | null;
  readonly maxValue?: number | null;
}

/** What a setting's leaf accepts once its `.default`, `.catch` and preprocess wrappers are peeled. */
type LeafShape =
  | { readonly kind: "number"; readonly min: number; readonly max: number }
  | { readonly kind: "values"; readonly values: readonly string[] }
  | { readonly kind: "members"; readonly values: readonly string[] };

function peel(node: SchemaNode): SchemaNode {
  const def = node._zod.def;
  if (def.type === "default" || def.type === "catch" || def.type === "prefault") {
    return peel(def.innerType as SchemaNode);
  }
  return def.type === "pipe" ? peel(def.out as SchemaNode) : node;
}

function enumValues(node: SchemaNode, key: string): readonly string[] {
  const def = node._zod.def;
  if (def.type === "boolean") {
    return ["false", "true"];
  }
  if (def.type === "enum" && def.entries !== undefined) {
    return Object.values(def.entries);
  }
  throw new Error(`appearance.${key}: an attribute channel needs a boolean, an enum or a list of an enum, not ${def.type}`);
}

function leafShape(key: string, leaf: SchemaNode): LeafShape {
  const node = peel(leaf);
  const def = node._zod.def;
  if (def.type === "number") {
    const { minValue, maxValue } = node;
    if (typeof minValue !== "number" || typeof maxValue !== "number") {
      throw new Error(`appearance.${key}: a property channel needs a bounded number`);
    }
    return { kind: "number", min: minValue, max: maxValue };
  }
  if (def.type === "array") {
    return { kind: "members", values: enumValues(peel(def.element as SchemaNode), key) };
  }
  return { kind: "values", values: enumValues(node, key) };
}

const SHAPE: Readonly<Record<string, SchemaNode>> = appearanceSettingsSchema.unwrap().shape as unknown as Readonly<Record<string, SchemaNode>>;
const DEFAULTS: Readonly<Record<string, unknown>> = appearanceSettingsSchema.parse({});

function shapeOf(row: AppearanceChannelRow): LeafShape {
  const leaf = SHAPE[row.key];
  if (leaf === undefined) {
    throw new Error(`appearance.${row.key} is not a schema leaf`);
  }
  return leafShape(row.key, leaf);
}

/** A variant matches the root that carries the value and everything under it; `:where()` adds no specificity. */
function variantRule(name: string, attributeSelector: string): string {
  return `@custom-variant ${name} (&:where(:root${attributeSelector}, :root${attributeSelector} *));`;
}

function renderProperty(row: AppearanceChannelRow, shape: LeafShape & { readonly kind: "number" }): string {
  const initial = DEFAULTS[row.key];
  if (typeof initial !== "number" || initial < shape.min || initial > shape.max) {
    throw new Error(`appearance.${row.key}: the default ${String(initial)} lies outside ${shape.min} to ${shape.max}`);
  }
  const unit = row.unit === "" ? "" : `, read as \`* 1${row.unit}\``;
  return [
    `/* appearance.${row.key}: ${shape.min} to ${shape.max}${unit} */`,
    `@property ${row.name} {`,
    '  syntax: "<number>";',
    "  inherits: true;",
    `  initial-value: ${initial};`,
    "}",
  ].join("\n");
}

function renderVariants(row: AppearanceChannelRow, shape: LeafShape): string {
  if (shape.kind === "number") {
    throw new Error(`appearance.${row.key}: a number reaches CSS as a property, not an attribute`);
  }
  const operator = shape.kind === "members" ? "~=" : "=";
  return shape.values.map((value) => variantRule(`${row.name.replace(/^data-/u, "")}-${value}`, `[${row.name}${operator}"${value}"]`)).join("\n");
}

/** Every `appearance-*` name the generated CSS declares, for the lint that refuses any other. */
export interface AppearanceChannelVocabulary {
  readonly properties: readonly string[];
  readonly attributes: readonly string[];
  readonly variants: readonly string[];
}

export function appearanceChannelVocabulary(): AppearanceChannelVocabulary {
  const variants = APPEARANCE_CHANNEL_ROWS.flatMap((row) => {
    if (row.kind !== "attribute") {
      return [];
    }
    const shape = shapeOf(row);
    return shape.kind === "number" ? [] : shape.values.map((value) => `${row.name.replace(/^data-/u, "")}-${value}`);
  });
  return {
    properties: APPEARANCE_CHANNEL_ROWS.filter((row) => row.kind === "property").map((row) => row.name),
    attributes: APPEARANCE_CHANNEL_ROWS.filter((row) => row.kind === "attribute").map((row) => row.name),
    variants,
  };
}

export function renderAppearanceChannelCss(): string {
  const blocks = APPEARANCE_CHANNEL_ROWS.map((row) => {
    const shape = shapeOf(row);
    if (row.kind === "property") {
      if (shape.kind !== "number") {
        throw new Error(`appearance.${row.key}: a property channel needs a number`);
      }
      return renderProperty(row, shape);
    }
    return renderVariants(row, shape);
  });
  return `${HEADER}\n\n${blocks.join("\n\n")}\n`;
}

if (process.argv[1]?.endsWith(APPEARANCE_CHANNEL_PATHS.producer)) {
  writeFileSync(join(REPO_ROOT, APPEARANCE_CHANNEL_PATHS.css), renderAppearanceChannelCss());
}
