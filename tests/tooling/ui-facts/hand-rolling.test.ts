/** `pnpm ui-facts --plan` or `--prove` through the CLI entry: the exit code and what it printed. */
function migrate(root: string, mode: "plan" | "prove", owner = "row.justify"): { readonly code: number; readonly printed: string } {
  const printed: string[] = [];
  const write = vi.spyOn(process.stdout, "write").mockImplementation((chunk) => {
    printed.push(String(chunk));
    return true;
  });
  try {
    return { code: runUiFacts([`--root=${root}`, "--out=census", `--${mode}=${owner}`, `--map=${MAP}`]), printed: printed.join("") };
  } finally {
    write.mockRestore();
  }
}

