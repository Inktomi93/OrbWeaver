/** The reasons a plan of one owner gives over planted doors, by line; a line with no reason is a planned site. */
function planned(root: string, owner: string, uses: readonly string[]): ReadonlyMap<number, string | null> {
  plant(root, { "components/uses.tsx": uses.join("\n") });
  migrate(root, "plan", owner);
  const plan = planOf(root);
  return new Map([...plan.sites.map(({ line }) => [line, null] as const), ...plan.review.map(({ line, reason }) => [line, reason] as const)]);
}

