/** The census through the CLI entry: `pnpm ui-facts --only=hand-rolling`, read back from the JSON it writes. */
function census(root: string, only = "hand-rolling"): { readonly hits: readonly Hit[]; readonly markdown: string } {
  const write = vi.spyOn(process.stdout, "write").mockImplementation(() => true);
  try {
    runUiFacts([`--root=${root}`, "--out=census", `--only=${only}`]);
  } finally {
    write.mockRestore();
  }
  const json = JSON.parse(readFileSync(join(root, "census/ui-facts.json"), "utf8")) as { readonly handRolling: readonly Hit[] };
  return { hits: json.handRolling, markdown: readFileSync(join(root, "census/ui-facts.md"), "utf8") };
}

const compare = (left: string, right: string): number => left.localeCompare(right);
const brief = (hit: Hit | undefined): readonly unknown[] => [hit?.category, hit?.verdict, hit?.owner];
const named = (hits: readonly Hit[], detail: string): Hit | undefined => hits.find((hit) => hit.detail === detail);

test("a sheet literal equal to a token is a token-literal naming it, and a structural value stays", ({ scratch }) => {
  const root = plantDir(scratch, "sheet-tokens");
  plant(root, {
    "styles/probe.css": [
      ".a {",
      "  transition-duration: 130ms;",
      "  z-index: 50;",
      "  opacity: 0.6;",
      "  padding-block: 24px;",
      "  border-width: 1px;",
      "  color: oklch(0.72 0.175 52);",
      "  background-color: oklch(from var(--surface) l c h / 0.4);",
      "}",
      "@container (min-width: 20rem) {",
      "  .a { margin: 0; inline-size: 100%; }",
      "}",
      ".b { transform: translateX(8px); }",
      "@supports (backdrop-filter: blur(1px)) {",
      "  .c { margin: 0; }",
      "}",
      "@media (prefers-reduced-motion: reduce) {",
      "  .d { animation-duration: 0.01ms; }",
      "}",
      "",
    ].join("\n"),
  });
  const { hits } = census(root);
  expect(brief(named(hits, "transition-duration: 130ms"))).toEqual(["token-literal", "token", "--motion-fast"]);
  expect(brief(named(hits, "z-index: 50"))).toEqual(["token-literal", "token", "--z-modal"]);
  // A token scoped to one purpose is not the owner of an equal value: 0.6 is "a receded element", and 1px is a control root's border arithmetic.
  expect(brief(named(hits, "opacity: 0.6"))).toEqual(["raw-value", "decide", "decide: opacity 0.6, only a purpose token holds it"]);
  expect(named(hits, "opacity: 0.6")?.reason).toContain("--opacity-receded");
  expect(brief(named(hits, "padding-block: 24px"))).toEqual(["token-literal", "token", "--spacing-section"]);
  expect(brief(named(hits, "border-width: 1px"))).toEqual(["raw-value", "decide", "decide: length 1px, only a purpose token holds it"]);
  expect(named(hits, "border-width: 1px")?.reason).toContain("--border-width-control");
  expect(brief(named(hits, "color: oklch(0.72 0.175 52)"))).toEqual(["token-literal", "token", "--color-primary"]);
  // A colour derived from a token is composition, so it stays.
  expect(named(hits, "background-color: oklch(from var(--surface) l c h/0.4)")?.keep).toBe("derived-colour");
  // A container condition cannot read a custom property, so it stays.
  expect(named(hits, "@container 20rem")?.keep).toBe("query-condition");
  // A feature test asks the browser; the reduced-motion floor is the shortest duration that still fires events.
  expect(named(hits, "backdrop-filter: blur(1px)")?.keep).toBe("feature-probe");
  expect(named(hits, "animation-duration: 0.01ms")?.keep).toBe("motion-floor");
  // Zero, a percentage and a transform are CSS structure: classified keep, each with its reason.
  expect([named(hits, "margin: 0")?.keep, named(hits, "inline-size: 100%")?.keep, named(hits, "transform: translateX(8px)")?.keep]).toEqual([
    "zero-sentinel",
    "relative-unit",
    "css-mechanism",
  ]);
});

test("a literal no token holds is a raw value asking for a new token, with the nearest token named", ({ scratch }) => {
  const root = plantDir(scratch, "raw-values");
  plant(root, {
    "styles/probe.css": ".a { padding-block: 18px; opacity: 0.5; }\n",
    "components/raw.ts": [
      'export const WIDTH = "20.5rem";',
      'export const PICK = "#abcdef";',
      'export const ANCHOR = "#review";',
      'export const NOTE = "wait 5 seconds";',
      'export const FILL_SENTINELS = ["#010203", "#030201"] as const;',
    ].join("\n"),
  });
  const { hits } = census(root);
  const padding = named(hits, "padding-block: 18px");
  expect(brief(padding)).toEqual(["raw-value", "token", "new token: length 18px"]);
  expect(padding?.reason).toContain("nearest is --spacing-section");
  expect(brief(named(hits, "opacity: 0.5"))).toEqual(["raw-value", "token", "new token: opacity 0.5"]);
  expect(brief(named(hits, '"20.5rem"'))).toEqual(["raw-value", "token", "new token: length 328px"]);
  expect(brief(named(hits, '"#abcdef"'))).toEqual(["raw-value", "token", "new token: colour #abcdef"]);
  // A sentinel is told apart from every real value on purpose; it is not a colour to tokenize.
  expect(named(hits, '"#010203"')?.keep).toBe("sentinel");
  // A URL fragment and a sentence are not values.
  expect(named(hits, '"#review"')).toBeUndefined();
  expect(named(hits, '"wait 5 seconds"')).toBeUndefined();
});

test("a class an arm of the element's own component writes is a recipe move; a class no arm writes is a new arm or no axis", ({ scratch }) => {
  const root = plantDir(scratch, "class-utilities");
  plant(root, {
    "components/uses.tsx": [
      'import { Grid, Row, Row as Line, Stack } from "@orb/ui/layout";',
      'import { Text } from "@orb/ui/text";',
      "export const A = () => (",
      "  <>",
      '    <Stack className="gap-row items-center flex px-row gap-section @cq-20:items-center" />',
      '    <Row className="justify-end items-start" />',
      '    <Grid className="items-center px-section" />',
      '    <Line className="justify-end" />',
      '    <Text className="truncate line-clamp-2">x</Text>',
      '    <Stack className="w-[18px] grid-cols-[minmax(0,1fr)_auto] opacity-100 py-px" />',
      "  </>",
      ");",
    ].join("\n"),
  });
  const { hits } = census(root);
  const classes = hits.filter((hit) => hit.category === "class-utility");
  // The owner names the element's own component, not the door family: Stack, Row and Grid are three tables.
  expect(brief(named(classes, "gap-row"))).toEqual(["class-utility", "recipe", "stack.gap"]);
  expect(named(classes, "gap-row")?.match).toBe("stack.gap.row");
  expect(brief(named(classes, "justify-end"))).toEqual(["class-utility", "recipe", "row.justify"]);
  expect(named(classes, "justify-end")?.match).toBe("row.justify.end");
  // Row declares align but forwards only gap and justify, and Grid declares no align: neither takes the prop, so neither is a recipe move.
  // The hit stays, owned by no axis, so a class never drops out of the census because its owner is not there.
  const onElement = (detail: string, name: string): Hit | undefined => classes.find((hit) => hit.detail === detail && hit.element?.name === name);
  expect(brief(onElement("items-center", "Stack"))).toEqual(["class-utility", "recipe", "stack.align"]);
  expect(brief(onElement("items-center", "Grid"))).toEqual(["class-utility", "decide", "no axis: items-center on grid"]);
  expect(brief(onElement("items-start", "Row"))).toEqual(["class-utility", "decide", "no axis: items-start on row"]);
  expect(brief(onElement("px-section", "Grid"))).toEqual(["class-utility", "decide", "no axis: px-section on grid"]);
  // An aliased import names the component its import exports, and the hit carries the import a rewrite must prove.
  const justified = classes.filter((hit) => hit.detail === "justify-end" && hit.element?.name === "Row");
  expect(justified.map((hit) => hit.owner)).toEqual(["row.justify", "row.justify"]);
  expect(justified[1]?.element).toMatchObject({ source: "@orb/ui/layout", name: "Row", carried: false });
  // The gap axis declares row and field; section is a valid spacing token with no arm. px belongs to paddingInline, not to padding.
  expect(brief(named(classes, "gap-section"))).toEqual(["class-utility", "decide", "new arm: stack.gap"]);
  expect(brief(named(classes, "px-row"))).toEqual(["class-utility", "recipe", "stack.paddingInline"]);
  expect(brief(named(classes, "@cq-20:items-center"))).toEqual(["class-utility", "decide", "new arm: stack.align, conditional"]);
  // A boolean axis owns its class, whatever the axis is called; a class one arm repeats beside others names no choice.
  expect(brief(named(classes, "truncate"))).toEqual(["class-utility", "recipe", "text.truncate"]);
  expect(named(classes, "truncate")?.match).toBe("text.truncate.true");
  expect(named(classes, "line-clamp-2")).toBeUndefined();
  expect(brief(named(classes, "w-[18px]"))).toEqual(["class-utility", "token", "new token: length 18px"]);
  // `flex` has no axis; a track formula, a visibility sentinel and the theme's px step are not hand-rolled values.
  expect(named(classes, "flex")).toBeUndefined();
  expect([named(classes, "grid-cols-[minmax(0,1fr)_auto]")?.keep, named(classes, "opacity-100")?.keep, named(classes, "py-px")?.keep]).toEqual([
    "css-mechanism",
    "zero-sentinel",
    "token-utility",
  ]);
});

