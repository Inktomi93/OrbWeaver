async function findings(rule: string, path: string, source: string, forced?: Linter.RuleSeverity): Promise<readonly Linter.LintMessage[]> {
  const filename = join(ROOT, path);
  const config = await eslint.calculateConfigForFile(filename);
  expect(config, path).toBeDefined();
  const messages = new Linter().verify(
    source,
    {
      files: ["**/*.{ts,tsx}"],
      plugins: config.plugins,
      languageOptions: { parser: tseslint.parser, parserOptions: { project: false, projectService: false, ecmaFeatures: { jsx: true } } },
      rules: { [rule]: forced ?? config.rules[rule] ?? "off" },
    },
    { filename },
  );
  expect(
    messages.filter(({ fatal }) => fatal === true),
    source,
  ).toEqual([]);
  return messages;
}

