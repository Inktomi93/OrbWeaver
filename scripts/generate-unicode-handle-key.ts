// Rebuilds packages/kit/src/handle-key/unicode-data.ts from the sha-pinned Unicode sources. The handle key mixes these
// tables with the engine's NFKC and NFD, so the pinned version must be the engine's; a bump re-keys users.handle_key.
// A source whose SHA-256 differs from its pin is refused before anything is written. There is no check mode: freshness
// needs the network.
import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import process from "node:process";
import { fileURLToPath } from "node:url";

const COMMAND = "node scripts/generate-unicode-handle-key.ts";
const OUTPUT_PATH = fileURLToPath(new URL("../packages/kit/src/handle-key/unicode-data.ts", import.meta.url));
const UNICODE_DATA_VERSION = "17.0.0";
const PUBLIC = `https://www.unicode.org/Public/${UNICODE_DATA_VERSION}`;

// Each source's URL and the SHA-256 it must have. A deliberate bump edits this table and UNICODE_DATA_VERSION together.
const SOURCES = {
  caseFolding: { url: `${PUBLIC}/ucd/CaseFolding.txt`, sha256: "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183" },
  derivedCore: { url: `${PUBLIC}/ucd/DerivedCoreProperties.txt`, sha256: "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08" },
  confusables: { url: `${PUBLIC}/security/confusables.txt`, sha256: "091c7f82fc39ef208faf8f94d29c244de99254675e09de163160c810d13ef22a" },
  aliases: { url: `${PUBLIC}/ucd/PropertyValueAliases.txt`, sha256: "64e9a5f76f7a1e8b5a47d6a1f9a26522a251208f5276bdfa1559dac7cf2e827a" },
} as const;
type SourceName = keyof typeof SOURCES;

// What each file says about its own version, so a download from another release refuses even with a matching pin.
const VERSION_MARKERS: Readonly<Record<SourceName, string>> = {
  caseFolding: `CaseFolding-${UNICODE_DATA_VERSION}.txt`,
  derivedCore: `DerivedCoreProperties-${UNICODE_DATA_VERSION}.txt`,
  confusables: `Version: ${UNICODE_DATA_VERSION}`,
  aliases: `PropertyValueAliases-${UNICODE_DATA_VERSION}.txt`,
};

const CASE_FOLDING_KEPT_STATUSES: ReadonlySet<string> = new Set(["C", "F"]);
const DEFAULT_IGNORABLE = "Default_Ignorable_Code_Point";
const SCRIPT_PROPERTY = "sc";
// `Hrkt` (Katakana_Or_Hiragana) is a Script value no code point carries, and `\p{scx=Hrkt}` does not compile.
const UNCARRIED_SCRIPTS: ReadonlySet<string> = new Set(["Hrkt"]);
const ENTRIES_PER_LINE = 64;
const HEX_RADIX = 16;

const sha256 = (text: string): string => createHash("sha256").update(text).digest("hex");

// The data lines of a UCD file: comments and blanks gone, fields split on `;` and trimmed.
function fields(text: string): readonly (readonly string[])[] {
  return text
    .split(/\r?\n/u)
    .map((line) => (line.split("#")[0] ?? "").trim())
    .filter((line) => line.length > 0)
    .map((line) => line.split(";").map((field) => field.trim()));
}

// A space-separated code point sequence, re-spelled in the one hex form the kit parser reads.
function sequence(field: string): string {
  return field
    .split(/\s+/u)
    .map((hex) => Number.parseInt(hex, HEX_RADIX).toString(HEX_RADIX))
    .join(" ");
}

// One exported array of `;`-joined entry lines, so the file stays diffable and inside the formatter's width.
function constant(name: string, doc: string, entries: readonly string[]): string {
  if (entries.length === 0) {
    throw new Error(`the ${name} table parsed empty; refusing to write a key that folds nothing`);
  }
  const lines: string[] = [];
  for (let at = 0; at < entries.length; at += ENTRIES_PER_LINE) {
    lines.push(`  ${JSON.stringify(entries.slice(at, at + ENTRIES_PER_LINE).join(";"))},`);
  }
  return `/** ${doc} */\nexport const ${name}: readonly string[] = [\n${lines.join("\n")}\n];\n`;
}

function render(sourceTexts: Readonly<Record<SourceName, string>>): string {
  const caseFolding = fields(sourceTexts.caseFolding)
    .filter(([, status]) => CASE_FOLDING_KEPT_STATUSES.has(status ?? ""))
    .map(([code, , mapping]) => `${sequence(code ?? "")}>${sequence(mapping ?? "")}`);
  const defaultIgnorable = fields(sourceTexts.derivedCore)
    .filter(([, property]) => property === DEFAULT_IGNORABLE)
    .map(([range]) => (range ?? "").split("..").map(sequence).join("-"));
  const confusables = fields(sourceTexts.confusables).map(([source, target]) => `${sequence(source ?? "")}>${sequence(target ?? "")}`);
  const scripts = fields(sourceTexts.aliases)
    .filter(([property, code]) => property === SCRIPT_PROPERTY && !UNCARRIED_SCRIPTS.has(code ?? ""))
    .map(([, code]) => code ?? "");
  return [
    `// GENERATED by \`${COMMAND}\`; do not hand-edit. Unicode ${UNICODE_DATA_VERSION}, from:`,
    ...(Object.keys(SOURCES) as SourceName[]).map((name) => `//   ${SOURCES[name].url} sha256 ${sha256(sourceTexts[name])}`),
    "// Entries are hex code points: `source>target` (a target may be a space-separated sequence), or `first-last`.",
    "",
    constant("CASE_FOLDING", "CaseFolding.txt, statuses C and F: the full case folding.", caseFolding),
    constant("DEFAULT_IGNORABLE", "DerivedCoreProperties.txt `Default_Ignorable_Code_Point` ranges.", defaultIgnorable),
    constant("CONFUSABLE_PROTOTYPES", "UTS 39 confusables.txt: each source code point's prototype.", confusables),
    constant("SCRIPT_CODES", "PropertyValueAliases.txt: every Script short code a code point can carry.", scripts),
  ].join("\n");
}

async function fetchSource(name: SourceName): Promise<string> {
  const { url } = SOURCES[name];
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${url} answered ${String(response.status)}`);
  }
  return await response.text();
}

const engine = process.versions["unicode"] ?? "unknown";
if (!UNICODE_DATA_VERSION.startsWith(`${engine}.`)) {
  throw new Error(
    `The engine speaks Unicode ${engine} but the pinned data is ${UNICODE_DATA_VERSION}; bump the pins to the engine's release and re-key users.handle_key`,
  );
}

const names = Object.keys(SOURCES) as SourceName[];
const downloaded = await Promise.all(names.map(fetchSource));
const texts = Object.fromEntries(names.map((name, at) => [name, downloaded[at] ?? ""])) as Record<SourceName, string>;

const mismatched = names.filter((name) => sha256(texts[name]) !== SOURCES[name].sha256);
if (mismatched.length > 0) {
  throw new Error(`${mismatched.join(", ")} differ from their pinned SHA-256; refusing to write. A deliberate bump updates SOURCES.`);
}
const unversioned = names.filter((name) => !texts[name].includes(VERSION_MARKERS[name]));
if (unversioned.length > 0) {
  throw new Error(`${unversioned.join(", ")} do not announce Unicode ${UNICODE_DATA_VERSION}; refusing to vendor a table from another release`);
}

await writeFile(OUTPUT_PATH, render(texts));
process.stdout.write(`wrote ${OUTPUT_PATH} from Unicode ${UNICODE_DATA_VERSION}\n`);
