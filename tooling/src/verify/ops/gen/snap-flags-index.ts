// Generator for `.claude/skills/snap-driving/reference/flags.md` (#1329, owner: "is there any way to gen
// snap's flags and args and help from the file so we don't have to upkeep this constantly?"). Before this,
// the file was hand-indexed from a `pnpm snap --help` read — accurate the day it was written, silently
// stale the next time a flag's meaning drifted from its row. Every row here is now read straight off
// `tooling/src/snap/ops/flag-grammar.ts`'s `snapFlagDescriptors()`, the SAME registry the help block and
// the argv parser derive from — so the index and the parser can never disagree about what a flag does.
//
// TWO ROWS ARE STATIC, not generated: `[route]` positional and `--report`/`--reports` are handled OUTSIDE
// the `FLAG_HANDLERS` dispatch table entirely (`lib/run-report-query.ts` intercepts `--report`/`--reports`
// before the arm/flag registry ever sees them; the bare route is a positional, never a flag), so they carry
// no `ArmFlagSpec`/`NonArmFlagMeta` row to derive from. They are appended verbatim after the generated
// groups — flagged in the file's own header so a reader is never fooled into thinking they drifted from a
// registry row that does not exist for them.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import process from "node:process";
import { refuseDirectInvocation } from "@orb/tooling/_shared/entrypoint";
import { EXIT } from "@orb/tooling/_shared/exit-contract";
import type { SnapFlagDescriptor } from "../../../snap/index.ts";
import { SNAP_FLAG_GROUP_ORDER, snapFlagDescriptors } from "../../../snap/index.ts";
import { SNAP_FLAGS_INDEX_REL } from "../../contract/ledger-paths.ts";

refuseDirectInvocation(import.meta.url, "node tooling/src/verify/cli.ts baseline snap-flags-index");

const REGEN_COMMAND = "pnpm exec node tooling/src/verify/cli.ts baseline snap-flags-index";

const GENERATED_HEADER = `<!-- GENERATED by ${REGEN_COMMAND} — do not edit; the registry is the source -->`;

const INTRO = `# Every snap flag, one line each (generated from the executable flag registry)

${GENERATED_HEADER}

\`pnpm snap --help\` prints the full contract, generated from the executable registry. This file is the
short index: every accepted flag and what it does. What a flag refuses to combine with is in the help
prose. When the two disagree, the help wins. Regenerate this file with
\`${REGEN_COMMAND}\`.

Shape legend: \`[@N]\` = page/context-targetable (\`--click@1\`); \`[x]\` optional value; \`<x>\` required value.
Exit codes everywhere: \`0\` clean · \`1\` red (a finding, a failed assertion, a failed step, a console error)
· \`2\` refused or tool error (the instrument could not measure — never a product verdict) · \`3\` misuse (your
argv is wrong; nothing ran; the \`ARG ERROR\` line names the fix).`;

/** `--flag <shape>` — the same shape rendering `snapFlagGrammarHelp()` uses, so the row and the printed
 *  grammar block never diverge on what a flag's argv looks like. */
function shapeOf(row: SnapFlagDescriptor): string {
  const suffix = row.pageTargetable ? " [@N]" : "";
  if (row.grammar === "required-value") {
    return `${row.flag}${suffix} <value>`;
  }
  if (row.grammar === "optional-name") {
    return `${row.flag}${suffix} [name]`;
  }
  if (row.grammar === "optional-selector") {
    return `${row.flag}${suffix} [selector]`;
  }
  if (row.grammar === "optional-value") {
    return `${row.flag}${suffix} [value]`;
  }
  return `${row.flag}${suffix}`;
}

function groupTable(group: string, rows: readonly SnapFlagDescriptor[]): string {
  const body = rows.map((row) => `| \`${shapeOf(row)}\` | ${row.summary} |`).join("\n");
  return `## ${group}\n\n| Flag | What it does |\n| - | - |\n${body}`;
}

/** One hand-written tail row: the first table cell verbatim, and its summary. */
interface StaticIndexRow {
  readonly cell: string;
  readonly summary: string;
}

/** The rows with NO registry descriptor behind them (this file's header says why). EXPORTED because the
 *  index's row census is a RELATIONSHIP, never a number: the derived file carries exactly one row per
 *  `snapFlagDescriptors()` entry PLUS these, and a pin that spells the sum as a literal goes stale the day
 *  a flag lands. #2492: it did — `--tap` (#2445) made the file 124 rows while the pin still said 123, so
 *  the suite sat red on a tree where nothing was wrong, and the only repair the number offers is the bump
 *  that re-arms it. Add a tail row here and the pin names it; add a flag to the registry and the pin
 *  follows, while `ledgers:fresh` owns the separate question of whether the COMMITTED file was
 *  regenerated. */
export const SNAP_FLAGS_INDEX_STATIC_ROWS: readonly StaticIndexRow[] = [
  {
    cell: "`[route]` positional",
    summary:
      "the app route to load — not a flag; the browser URL only ever settles at `/` or `/login`; `/$section` is a deep-link alias that redirects to `/` before render",
  },
  {
    cell: "`--report <run.json path\\|run-id\\|latest>`",
    summary: "replay one immutable run index (`lib/run-report-query.ts` intercepts this before the flag registry)",
  },
  { cell: "`--reports`", summary: "list every indexed run across registered worktrees" },
];

const STATIC_TAIL = `## Read back (browser-free — parsed outside the flag registry, see this file's header)

| Flag | What it does |
| - | - |
${SNAP_FLAGS_INDEX_STATIC_ROWS.map((row) => `| ${row.cell} | ${row.summary} |`).join("\n")}

## Regenerate this file

\`\`\`bash
${REGEN_COMMAND}
\`\`\`
`;

/** The whole markdown body, deterministic given the registry — the single input `generateSnapFlagsIndex`
 *  and `ledgers-fresh`'s drift check both read, so they can never disagree. */
export function deriveSnapFlagsIndexMarkdown(): string {
  const rows = snapFlagDescriptors();
  const byGroup = new Map<string, SnapFlagDescriptor[]>();
  for (const row of rows) {
    const bucket = byGroup.get(row.group) ?? [];
    bucket.push(row);
    byGroup.set(row.group, bucket);
  }
  const groups = [...byGroup.keys()].sort((a, b) => SNAP_FLAG_GROUP_ORDER.indexOf(a) - SNAP_FLAG_GROUP_ORDER.indexOf(b));
  const tables = groups.map((group) => groupTable(group, byGroup.get(group) ?? []));
  return `${INTRO}\n\n${tables.join("\n\n")}\n\n${STATIC_TAIL}`;
}

/** The `baseline snap-flags-index` verb — the SINGLE writer of the committed flag index (GATE-AUTHORING §4.8). */
export function generateSnapFlagsIndex(root: string): number {
  const markdown = deriveSnapFlagsIndexMarkdown();
  const out = join(root, SNAP_FLAGS_INDEX_REL);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, markdown);
  process.stdout.write(`wrote ${snapFlagDescriptors().length} flag rows → ${out}\n`);
  return EXIT.clean;
}
