/** Collapse newlines/repeated space to one line and drop backticks — the PURPOSE column is a truncated
 *  summary, and a code span the truncation cuts in half would leave a bare, unescaped backtick
 *  (`check:docs`'s "reaching TEXT, not a code-span delimiter" refusal). Run BEFORE truncation, so the
 *  length limit measures the text a reader actually sees. */
function clean(text: string): string {
  return text.replace(/\s+/gu, " ").trim().replaceAll("`", "");
}

/** Escape every character `pnpm format:docs` would otherwise escape outside a code span: the cell
 *  delimiter, every `*` (CommonMark emphasis), and a `<` immediately followed by a letter or `/` (the
 *  formatter's own "looks like an HTML tag" heuristic — a bare comparison `<=`/`<N` with no following
 *  letter is left alone). An intraword `_` is NOT escaped: CommonMark's own intraword rule already
 *  refuses it as emphasis, and the formatter leaves it bare. Run AFTER truncation, so an inserted `\`
 *  never lands on the cut point. */
function escapeCell(text: string): string {
  return text
    .replaceAll("|", "\\|")
    .replaceAll(/\*/gu, "\\*")
    .replaceAll(/<(?=[A-Za-z/])/gu, "\\<");
}

/** A short population summary — the roots a gate reads, with a trailing `*` when a `PopulationExpr`
 *  object narrows further (`under`/`named`/`ext`/…). Full narrowing detail belongs to the module header,
 *  which owns the actual predicate; this column is a directory entry, not the population contract. */
function populationSummary(expr: PopulationExpr): string {
  if (typeof expr === "string") {
    return expr;
  }
  if (Array.isArray(expr)) {
    return expr.join(",");
  }
  if ("of" in expr) {
    return expr.of;
  }
  if (!("in" in expr)) {
    return "?";
  }
  const narrowed = ["not", "under", "notUnder", "named", "notNamed", "ext", "notExt", "depth"].some((key) => key in expr);
  return `${expr.in.join(",")}${narrowed ? "*" : ""}`;
}

/** `authority/severity`, e.g. `hard/error` or `reviewed-grant/warning` — one column instead of two, since
 *  every combination but `hard`+`warning` is valid and the pair reads as one fact. */
function authoritySeverity(authority: GateAuthority, severity: string): string {
  return `${authority}/${severity}`;
}

/** A one-line purpose, truncated at a word boundary. The descriptor's `message` is written for the agent
 *  who TRIPPED the gate, so it runs long (the corpus averages ~325 chars, some over 1,000); this index is
 *  a directory, not the finding text, so it is deliberately cut short. */
const PURPOSE_LIMIT = 38;
function purposeOf(gate: GatePolicy): string {
  const text = clean(gate.message);
  if (text.length <= PURPOSE_LIMIT) {
    return escapeCell(text);
  }
  const cut = text.slice(0, PURPOSE_LIMIT);
  const lastSpace = cut.lastIndexOf(" ");
  return `${escapeCell(cut.slice(0, lastSpace > PURPOSE_LIMIT / 2 ? lastSpace : PURPOSE_LIMIT))}…`;
}

function row(gate: GatePolicy): string {
  const family = gate.family === gate.id ? "—" : escapeCell(gate.family);
  return `| \`${gate.id}\` | ${family} | ${authoritySeverity(gate.authority, gate.severity)} | ${escapeCell(populationSummary(gate.population))} | ${purposeOf(gate)} |`;
}

/** Sorted by id — a stable, reviewable diff order with no dependence on file-discovery order. */
export function deriveActiveGatesIndexMarkdown(gates: readonly GatePolicy[]): string {
  const sorted = [...gates].sort((a, b) => a.id.localeCompare(b.id));
  const table = [
    `(${sorted.length} registered gates)`,
    "",
    "| Gate | Family | Authority/Severity | Population | Purpose |",
    "| - | - | - | - | - |",
    ...sorted.map(row),
  ].join("\n");
  return `${HEADER}${table}\n${ELEVATED_ALLOW_NOTE}${TAIL}`;
}

export async function deriveActiveGatesIndex(root: string): Promise<string> {
  const corpus = await loadGateCorpus(root);
  return deriveActiveGatesIndexMarkdown(corpus.gates);
}

/** The `baseline active-gates-index` verb — the SINGLE writer of the committed doc (GATE-AUTHORING §4.8). */
export async function generateActiveGatesIndex(root: string): Promise<number> {
  const markdown = await deriveActiveGatesIndex(root);
  const out = join(root, ACTIVE_GATES_INDEX_REL);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, markdown);
  process.stdout.write(`wrote the active-gates index → ${out}\n`);
  return EXIT.clean;
}
