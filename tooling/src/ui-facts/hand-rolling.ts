// The hand-rolling census: every hand-written design value, class, style, pattern and constant, each with the owner that would retire it.
import { classHits } from "./hand-classes.ts";
import { codeFindings, constantHits } from "./hand-code.ts";
import type { Hit } from "./hand-model.ts";
import { byPlace, hitOf } from "./hand-model.ts";
import { sheetHits } from "./hand-sheets.ts";
import { styleHits } from "./hand-style.ts";
import type { Site } from "./sites.ts";
import { KINDS } from "./sites.ts";
import type { Source } from "./source.ts";
import { elementsOf } from "./source.ts";
import type { ValueTokens } from "./tokens.ts";
import type { ComponentTables } from "./variant-tables.ts";

/** Site kinds that are a hand-built pattern a primitive owns: a raw element, or a drawing the icon set draws. */
const PATTERN_KINDS: ReadonlySet<string> = new Set(
  Object.entries(KINDS)
    .filter(([kind, info]) => (info.area === "B" || kind === "inline-svg") && info.replacement !== null)
    .map(([kind]) => kind),
);

// A generated file says so in its header. Its literals are what its generator emits, and the generator is the owner.
const GENERATED_HEADER = /GENERATED by [^\n]{0,80}DO NOT EDIT/u;
const HEADER_BYTES = 300;

export interface CensusInputs {
  readonly sources: readonly Source[];
  /** The A and B sites the audit read, after exceptions. */
  readonly sites: readonly Site[];
  readonly tokens: ValueTokens;
  readonly components: ComponentTables;
  readonly referenced: ReadonlySet<string>;
}

function patternHits(sites: readonly Site[]): readonly Hit[] {
  return sites
    .filter((site) => site.layer === "client" && !site.ownerLayer && PATTERN_KINDS.has(site.kind))
    .map((site) => {
      const info = KINDS[site.kind];
      const owner = info?.replacement ?? site.kind;
      return hitOf(
        { path: site.path, line: site.line, section: site.section, layer: site.layer },
        { category: "hand-built", where: "element", detail: site.detail },
        { verdict: "primitive", match: owner, owner, reason: `${info?.what ?? site.kind}: ${owner} owns it`, keep: null },
      );
    });
}

function sourceHits(source: Source, inputs: CensusInputs): { readonly hits: readonly Hit[]; readonly constants: ReturnType<typeof codeFindings>["constants"] } {
  if (source.kind === "css") {
    return { hits: sheetHits(source, inputs.tokens), constants: [] };
  }
  const code = codeFindings(source, inputs.tokens);
  const sf = source.sf;
  const styles = source.kind === "tsx" && sf !== null ? elementsOf(sf).flatMap((elem) => styleHits(source, sf, elem, inputs.tokens)) : [];
  // Several elements can wear one style object; it is one write.
  const written = new Map(styles.map((hit) => [`${hit.line}|${hit.detail}`, hit]));
  return { hits: [...code.hits, ...written.values()], constants: code.constants };
}

/** Every hit in the sources, sorted by place. */
export function buildHandRolling(inputs: CensusInputs): readonly Hit[] {
  const authored = inputs.sources.filter((source) => !GENERATED_HEADER.test(source.text.slice(0, HEADER_BYTES)));
  const parts = authored.map((source) => sourceHits(source, inputs));
  const constants = parts.flatMap((part) => part.constants);
  const code = authored.filter((source) => source.kind !== "css");
  const classes = classHits(code, { tokens: inputs.tokens, components: inputs.components, referenced: inputs.referenced });
  return [...parts.flatMap((part) => part.hits), ...constantHits(constants, inputs.tokens), ...classes, ...patternHits(inputs.sites)].toSorted(byPlace);
}
