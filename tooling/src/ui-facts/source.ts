// The read-only file inventory and the syntactic JSX helpers every ui-facts scan shares. Syntax only: no program, no checker.
import { globSync, readFileSync } from "node:fs";
import { join } from "node:path";
import ts from "typescript";

const SCAN_ROOTS = ["packages/client/src", "packages/ui/src"] as const;

const LAYERS = ["client", "ui"] as const;
export type Layer = (typeof LAYERS)[number];
const FILE_KINDS = ["ts", "tsx", "css"] as const;
type FileKind = (typeof FILE_KINDS)[number];

export interface Source {
  readonly path: string;
  readonly text: string;
  readonly kind: FileKind;
  readonly layer: Layer;
  /** The feature name, or `client:<dir>` / `ui:<dir>` outside the features. */
  readonly section: string;
  readonly sf: ts.SourceFile | null;
}

// Tests, stories and generated bytes are not authored UI: generator output is fixed in its generator.
const SKIPPED = /\.(?:test|stories|story|gen)\.|\.d\.ts$|\/node_modules\//u;

function sectionOf(path: string): string {
  const feature = /^packages\/client\/src\/features\/([^/]+)\//u.exec(path);
  if (feature?.[1] !== undefined) {
    return feature[1];
  }
  const other = /^packages\/(client|ui)\/src\/([^/]+)/u.exec(path);
  return other?.[1] === undefined || other[2] === undefined ? "other" : `${other[1]}:${other[2].replace(/\.[a-z]+$/u, "")}`;
}

function parse(relative: string, text: string, kind: FileKind): ts.SourceFile | null {
  if (kind === "css") {
    return null;
  }
  return ts.createSourceFile(relative, text, ts.ScriptTarget.ES2022, true, kind === "tsx" ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
}

function sourcesUnder(root: string, scanRoot: string, kind: FileKind): readonly Source[] {
  const layer: Layer = scanRoot.includes("client") ? "client" : "ui";
  return globSync(`${scanRoot}/**/*.${kind}`, { cwd: root })
    .sort()
    .filter((relative) => !SKIPPED.test(relative))
    .map((relative) => {
      const text = readFileSync(join(root, relative), "utf8");
      return { path: relative, text, kind, layer, section: sectionOf(relative), sf: parse(relative, text, kind) };
    });
}

export function loadSources(root: string): readonly Source[] {
  return SCAN_ROOTS.flatMap((scanRoot) => FILE_KINDS.flatMap((kind) => sourcesUnder(root, scanRoot, kind)));
}

export const lineOf = (sf: ts.SourceFile, node: ts.Node): number => sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1;

export function visit(node: ts.Node, each: (node: ts.Node) => void): void {
  each(node);
  ts.forEachChild(node, (child) => visit(child, each));
}

const ELEMENT_KINDS = ["raw", "ui", "composite", "local"] as const;
type ElementKind = (typeof ELEMENT_KINDS)[number];

export interface Elem {
  readonly tag: string;
  readonly kind: ElementKind;
  /** The `@orb/ui/<door>` the tag came from, when it is a ui element. */
  readonly door: string | null;
  readonly line: number;
  readonly opening: ts.JsxOpeningLikeElement;
  readonly element: ts.JsxElement | ts.JsxSelfClosingElement;
  readonly attrs: ReadonlyMap<string, ts.JsxAttribute>;
  readonly hasSpread: boolean;
  /** The expression of every `{...x}` attribute, in source order. */
  readonly spreads: readonly ts.Expression[];
}

function importsOf(sf: ts.SourceFile): ReadonlyMap<string, string> {
  const map = new Map<string, string>();
  for (const statement of sf.statements) {
    if (!(ts.isImportDeclaration(statement) && ts.isStringLiteral(statement.moduleSpecifier))) {
      continue;
    }
    const from = statement.moduleSpecifier.text;
    const clause = statement.importClause;
    if (clause?.name !== undefined) {
      map.set(clause.name.text, from);
    }
    const bindings = clause?.namedBindings;
    if (bindings !== undefined && ts.isNamedImports(bindings)) {
      for (const specifier of bindings.elements) {
        map.set(specifier.name.text, from);
      }
    }
  }
  return map;
}

function doorOf(from: string): string | null {
  const match = /^@orb\/ui\/([^/]+)/u.exec(from);
  return match?.[1] ?? null;
}

function kindOf(tag: string, imports: ReadonlyMap<string, string>): { readonly kind: ElementKind; readonly door: string | null } {
  const root = tag.split(".")[0] ?? tag;
  if (/^[a-z]/u.test(root)) {
    return { kind: "raw", door: null };
  }
  const from = imports.get(root);
  if (from === undefined) {
    return { kind: "local", door: null };
  }
  const door = doorOf(from);
  if (door !== null) {
    return { kind: "ui", door };
  }
  return from === "#components" || /\/components\//u.test(from) ? { kind: "composite", door: null } : { kind: "local", door: null };
}

export function elementsOf(sf: ts.SourceFile): readonly Elem[] {
  const imports = importsOf(sf);
  const out: Elem[] = [];
  visit(sf, (node) => {
    if (!(ts.isJsxSelfClosingElement(node) || ts.isJsxElement(node))) {
      return;
    }
    const opening = ts.isJsxElement(node) ? node.openingElement : node;
    const attrs = new Map<string, ts.JsxAttribute>();
    const spreads: ts.Expression[] = [];
    for (const attribute of opening.attributes.properties) {
      if (ts.isJsxAttribute(attribute)) {
        attrs.set(attribute.name.getText(sf), attribute);
      } else {
        spreads.push(attribute.expression);
      }
    }
    const tag = opening.tagName.getText(sf);
    out.push({ tag, ...kindOf(tag, imports), line: lineOf(sf, opening), opening, element: node, attrs, hasSpread: spreads.length > 0, spreads });
  });
  return out;
}

/** The literal string of an attribute (`a="x"`, `a={"x"}`, a no-substitution template), else undefined. */
export function attrString(attribute: ts.JsxAttribute | undefined): string | undefined {
  const init = attribute?.initializer;
  if (init === undefined) {
    return undefined;
  }
  if (ts.isStringLiteral(init)) {
    return init.text;
  }
  if (
    ts.isJsxExpression(init) &&
    init.expression !== undefined &&
    (ts.isStringLiteral(init.expression) || ts.isNoSubstitutionTemplateLiteral(init.expression))
  ) {
    return init.expression.text;
  }
  return undefined;
}

/** `a`, `a={true}` read as "true"; `a={false}` as "false"; a literal as its text; anything computed as null. */
export function attrValue(attribute: ts.JsxAttribute): string | null {
  const text = attrString(attribute);
  if (text !== undefined) {
    return text;
  }
  const init = attribute.initializer;
  if (init === undefined) {
    return "true";
  }
  if (ts.isJsxExpression(init) && init.expression !== undefined) {
    if (init.expression.kind === ts.SyntaxKind.TrueKeyword) {
      return "true";
    }
    if (init.expression.kind === ts.SyntaxKind.FalseKeyword) {
      return "false";
    }
    if (ts.isNumericLiteral(init.expression)) {
      return init.expression.text;
    }
  }
  return null;
}

/** The literal text a JSX element shows: JsxText and string-literal expressions, joined and collapsed. */
export function childrenText(element: ts.JsxElement | ts.JsxSelfClosingElement): string | null {
  if (ts.isJsxSelfClosingElement(element)) {
    return null;
  }
  const parts: string[] = [];
  for (const child of element.children) {
    if (ts.isJsxText(child)) {
      parts.push(child.text);
    } else if (ts.isJsxExpression(child) && child.expression !== undefined) {
      if (ts.isStringLiteral(child.expression) || ts.isNoSubstitutionTemplateLiteral(child.expression)) {
        parts.push(child.expression.text);
      } else {
        return null;
      }
    } else {
      return null;
    }
  }
  const text = parts.join(" ").replace(/\s+/gu, " ").trim();
  return text === "" ? null : text;
}
